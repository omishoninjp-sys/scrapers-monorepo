    def legacy_sku_keys(self, product):
        """
        舊 scraper 的 SKU 有**兩種格式混在同一個 collection 裡**：
          FGT-434            normalize_sku 去掉前導零後的形式
          FGT-000000000434   更早期沒正規化、直接用原始商品編號的形式
        兩種都列出來比對。同一商品若兩種都存在，遷移只會改到其中一件，
        另一件會回報「新 SKU 已被占用」，之後由清理階段當成已下架刪除 ——
        那本來就是重複資料，刪掉是對的。
        """
        raw = str(product.sku or "")
        keys = [f"FGT-{raw}"]
        try:
            keys.insert(0, f"FGT-{int(raw)}")
        except (TypeError, ValueError):
            pass
        return list(dict.fromkeys(keys))

