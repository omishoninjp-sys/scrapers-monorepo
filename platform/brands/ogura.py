    def extract_weights(self, soup):
        """小倉標示格式：【寸法】タテ○×ヨコ○×高さ○ mm 、【重量】○ kg"""
        text = self.scope(soup).get_text()
        volume = actual = 0.0
        m = re.search(r"【寸法】[タテ縦]*(\d+(?:\.\d+)?)[×xX][ヨコ横]*(\d+(?:\.\d+)?)"
                      r"[×xX][高さ]*(\d+(?:\.\d+)?)\s*mm", text)
        if m:
            h, w, d = (float(m.group(i)) for i in (1, 2, 3))
            volume = (h * w * d) / 6_000_000
        m = re.search(r"【重量】(\d+(?:\.\d+)?)\s*kg", text)
        if m:
            actual = float(m.group(1))
        return actual, volume
